"""
Generates the app's original launcher icon as Android vector drawables (adaptive icon layers).
Run from the repo root:  py tools/icon/make_icon.py
Writes app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml.
"""
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res/drawable"

# 108dp adaptive canvas; launchers may crop to the central 66dp, so the art stays inside it.
CELL, GAP = 17.0, 2.5
GRID = 3 * CELL + 2 * GAP
ORIGIN = (108 - GRID) / 2

# (row, col, face colour, lip colour, highlight colour) — the game's tile palette.
BLOCKS = [
    (0, 1, "#FF6B5A", "#B34B3F", "#FFA69C"),
    (0, 2, "#FFC145", "#B38730", "#FFDA8F"),
    (1, 0, "#3FC8F2", "#2C8CA9", "#8CDEF7"),
    (1, 1, "#5BD97A", "#409855", "#9DE8AF"),
    (1, 2, "#8C7BFF", "#6256B3", "#BAB0FF"),
    (2, 0, "#FF9F43", "#B36F2F", "#FFC48E"),
    (2, 2, "#FF7FC8", "#B3598C", "#FFB3DE"),
]


def rrect(x, y, w, h, r):
    return (f"M{x + r:.2f},{y:.2f} h{w - 2 * r:.2f} a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{r:.2f} "
            f"v{h - 2 * r:.2f} a{r:.2f},{r:.2f} 0 0 1 -{r:.2f},{r:.2f} h-{w - 2 * r:.2f} "
            f"a{r:.2f},{r:.2f} 0 0 1 -{r:.2f},-{r:.2f} v-{h - 2 * r:.2f} a{r:.2f},{r:.2f} 0 0 1 {r:.2f},-{r:.2f} z")


def block_paths(row, col, face, lip, shine, mono=None):
    x = ORIGIN + col * (CELL + GAP)
    y = ORIGIN + row * (CELL + GAP)
    r = CELL * 0.22
    if mono:
        return [f'    <path android:fillColor="{mono}" android:pathData="{rrect(x, y, CELL, CELL, r)}" />']
    return [
        f'    <path android:fillColor="{lip}" android:pathData="{rrect(x, y, CELL, CELL, r)}" />',
        f'    <path android:fillColor="{face}" android:pathData="{rrect(x, y, CELL, CELL * 0.86, r)}" />',
        f'    <path android:fillColor="{shine}" android:pathData="{rrect(x + CELL * 0.16, y + CELL * 0.1, CELL * 0.68, CELL * 0.17, CELL * 0.08)}" />',
    ]


def vector(paths, extra_ns=""):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/icon/make_icon.py: original artwork. Do not edit by hand. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            + "\n".join(paths) + "\n</vector>\n")


def main():
    background = [
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="108">\n'
        '                <item android:offset="0" android:color="#FF2E2470" />\n'
        '                <item android:offset="1" android:color="#FF15123A" />\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>',
    ]
    foreground = [p for b in BLOCKS for p in block_paths(*b)]
    monochrome = [p for b in BLOCKS for p in block_paths(*b, mono="#FFFFFFFF")]

    RES.mkdir(parents=True, exist_ok=True)
    (RES / "ic_launcher_background.xml").write_text(vector(background, '\n    xmlns:aapt="http://schemas.android.com/aapt"'), encoding="utf-8")
    (RES / "ic_launcher_foreground.xml").write_text(vector(foreground), encoding="utf-8")
    (RES / "ic_launcher_monochrome.xml").write_text(vector(monochrome), encoding="utf-8")
    print("wrote launcher icon layers")


if __name__ == "__main__":
    main()
